export const exportTrainingsToPDF = async (trainings: Training[], filename: string = 'trainings', userName?: string) => {
  const headers = ['Title', 'Type', 'Date', 'Location', 'Duration', 'Trainer', 'Attendees'];
  const rows: (string | number)[][] = trainings.map(training => [
    training.title,
    training.type || training.training_type || '',
    new Date(training.date || training.scheduled_date || '').toLocaleDateString(),
    training.location || training.venue || '',
    `${training.duration || training.duration_hours || 0} hrs`,
    training.trainerName ?? '',
    (training.attendees?.length || 0).toString(),
  ]);

  // Prepare chart data
  const typeData: Record<string, number> = {};
  const statusData: Record<string, number> = {};
  
  trainings.forEach(t => {
    const type = t.type || t.training_type || 'Unknown';
    const status = t.status || 'Unknown';
    typeData[type] = (typeData[type] || 0) + 1;
    statusData[status] = (statusData[status] || 0) + 1;
  });

  const typeChartData: ChartDataItem[] = Object.entries(typeData)
    .map(([name, value]) => ({ name, value }));

  const totalAttendees = trainings.reduce((sum, t) => sum + (t.attendees?.length || 0), 0);
  const totalHours = trainings.reduce((sum, t) => sum + (t.duration || t.duration_hours || 0), 0);

  await exportToPDFWithCharts({
    title: 'Trainings Report',
    headers,
    rows,
    filename,
    userName,
    summaryStats: [
      { label: 'Total Trainings', value: trainings.length },
      { label: 'Total Attendees', value: totalAttendees },
      { label: 'Total Hours', value: totalHours },
      { label: 'Completed', value: trainings.filter(t => t.status?.toLowerCase() === 'completed').length },
    ],
    charts: [
      { type: 'pie', data: typeChartData, title: 'Trainings by Type' },
    ],
  });
};

