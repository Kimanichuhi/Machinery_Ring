// Helper to get MR name
const getMrName = (localMrId: string, localMrName?: string) => {
  return localMrName || localMrId || 'Unknown';
};

const formatDate = (value?: Date | string | null) => {
  if (!value) return '';
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? '' : date.toLocaleDateString();
};

const formatMoney = (value?: number | string | null) => {
  const amount = Number(value || 0);
  return Number.isFinite(amount) ? amount.toLocaleString() : '0';
};

const truncateText = (value?: string | null, maxLength = 42) => {
  const text = value?.trim() || '';
  return text.length > maxLength ? `${text.slice(0, maxLength - 3)}...` : text;
};

// Load logo as base64 for PDF
const loadLogoAsBase64 = async (): Promise<string | null> => {
  try {
    const response = await fetch(MR_LOGO_PATH);
    const blob = await response.blob();
    return new Promise((resolve) => {
      const reader = new FileReader();
      reader.onloadend = () => resolve(reader.result as string);
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
};

// Add chart image to PDF
const addChartToPDF = (
  doc: jsPDF,
  chartBase64: string | null,
  x: number,
  y: number,
  width: number,
  height: number
): number => {
  if (chartBase64) {
    try {
      doc.addImage(chartBase64, 'PNG', x, y, width, height);
      return y + height + 10;
    } catch (e) {
      console.warn('Failed to add chart to PDF:', e);
    }
  }
  return y;
};

