export const exportFarmersToPDF = async (farmers: Farmer[], filename: string = 'farmers', userName?: string) => {
  const headers = ['Name', 'Phone', 'Local MR', 'Location', 'Value Chain', 'Category', 'Rating', 'Trainings'];
  const rows: (string | number)[][] = farmers.map(farmer => [
    farmer.name,
    farmer.phone || '',
    getMrName(farmer.localMrId || '', farmer.localMrName),
    `${farmer.location?.village || farmer.village || ''}, ${farmer.location?.county || farmer.county || ''}`,
    farmer.valueChain || farmer.farming_type || '',
    farmer.farmerCategory || '',
    farmer.farmerRating || '',
    (farmer.trainingsAttended || farmer.trainings_attended || 0).toString(),
  ]);

  // Prepare chart data
  const countyData: Record<string, number> = {};
  const valueChainData: Record<string, number> = {};
  const categoryData: Record<string, number> = {};
  
  farmers.forEach(f => {
    const county = f.location?.county || f.county || 'Unknown';
    const valueChain = f.valueChain || f.farming_type || 'Unknown';
    const category = f.farmerCategory || 'Unknown';
    
    countyData[county] = (countyData[county] || 0) + 1;
    valueChainData[valueChain] = (valueChainData[valueChain] || 0) + 1;
    categoryData[category] = (categoryData[category] || 0) + 1;
  });

  const countyChartData: ChartDataItem[] = Object.entries(countyData)
    .map(([name, value]) => ({ name, value }))
    .sort((a, b) => b.value - a.value);
  
  const valueChainChartData: ChartDataItem[] = Object.entries(valueChainData)
    .map(([name, value]) => ({ name, value }))
    .sort((a, b) => b.value - a.value);

  await exportToPDFWithCharts({
    title: 'Farmers Report',
    headers,
    rows,
    filename,
    userName,
    summaryStats: [
      { label: 'Total Farmers', value: farmers.length },
      { label: 'Counties', value: Object.keys(countyData).length },
      { label: 'Value Chains', value: Object.keys(valueChainData).length },
      { label: 'Active', value: farmers.filter(f => f.farmerRating === 'Active' || f.status === 'active').length },
    ],
    charts: [
      { type: 'pie', data: valueChainChartData, title: 'Farmers by Value Chain' },
      { type: 'horizontal-bar', data: countyChartData, title: 'Farmers by County' },
    ],
  });
};

