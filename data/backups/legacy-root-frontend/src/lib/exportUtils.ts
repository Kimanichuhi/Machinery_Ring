// Enhanced PDF export with charts
interface PDFExportOptions {
  title: string;
  headers: string[];
  rows: (string | number)[][];
  filename: string;
  userName?: string;
  charts?: {
    type: 'bar' | 'pie' | 'line' | 'horizontal-bar' | 'summary';
    data: ChartDataItem[] | { label: string; value: string | number }[];
    title: string;
    dataKeys?: string[];
  }[];
  summaryStats?: { label: string; value: string | number }[];
}

const exportToPDFWithCharts = async (options: PDFExportOptions) => {
  const { title, headers, rows, filename, userName, charts = [], summaryStats } = options;
  const doc = new jsPDF('landscape');
  const logoBase64 = await loadLogoAsBase64();
  
  // Page 1: Header with logo and summary
  let currentY = 15;
  
  // Add logo
  if (logoBase64) {
    try {
      doc.addImage(logoBase64, 'PNG', 14, 10, 35, 18);
      currentY = 32;
    } catch (e) {
      console.warn('Failed to add logo:', e);
    }
  }
  
  // Title
  doc.setFontSize(20);
  doc.setTextColor(34, 139, 34);
  doc.text(title, logoBase64 ? 55 : 14, currentY);
  
  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text(`Generated: ${new Date().toLocaleDateString()} | Total Records: ${rows.length}`, logoBase64 ? 55 : 14, currentY + 8);
  if (userName) {
    doc.text(`Generated by: ${userName}`, logoBase64 ? 55 : 14, currentY + 14);
  }
  
  currentY += userName ? 25 : 18;
  
  // Add summary stats card if provided
  if (summaryStats && summaryStats.length > 0) {
    const summaryChart = await renderSummaryCard(summaryStats, 'Report Summary');
    currentY = addChartToPDF(doc, summaryChart, 14, currentY, 180, 40);
  }
  
  // Add charts
  let chartX = 14;
  let chartRowY = currentY;
  
  for (let i = 0; i < charts.length; i++) {
    const chart = charts[i];
    let chartImage: string | null = null;
    
    switch (chart.type) {
      case 'bar':
        chartImage = await renderSalesBarChart(chart.data as ChartDataItem[]);
        break;
      case 'pie':
        chartImage = await renderPieChart(chart.data as ChartDataItem[], chart.title);
        break;
      case 'line':
        chartImage = await renderLineChart(chart.data as ChartDataItem[], chart.title, chart.dataKeys);
        break;
      case 'horizontal-bar':
        chartImage = await renderHorizontalBarChart(chart.data as ChartDataItem[], chart.title);
        break;
    }
    
    if (chartImage) {
      const chartWidth = chart.type === 'pie' ? 130 : 140;
      const chartHeight = 80;
      
      // Check if we need a new row
      if (chartX + chartWidth > 280) {
        chartX = 14;
        chartRowY += chartHeight + 5;
      }
      
      // Check if we need a new page
      if (chartRowY + chartHeight > 190) {
        doc.addPage();
        chartRowY = 20;
        chartX = 14;
      }
      
      addChartToPDF(doc, chartImage, chartX, chartRowY, chartWidth, chartHeight);
      chartX += chartWidth + 5;
    }
  }
  
  // Add new page for data table
  doc.addPage();
  
  // Data table
  autoTable(doc, {
    head: [headers],
    body: rows,
    startY: 20,
    styles: { fontSize: 8, cellPadding: 2 },
    headStyles: { fillColor: [34, 139, 34], textColor: 255 },
    alternateRowStyles: { fillColor: [245, 245, 245] },
    margin: { left: 14, right: 14 },
  });

  // Footer on all pages
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setTextColor(128);
    doc.text('MR Dashboard - Confidential', 14, doc.internal.pageSize.height - 10);
    doc.text(`Page ${i} of ${pageCount}`, doc.internal.pageSize.width - 35, doc.internal.pageSize.height - 10);
  }

  doc.save(`${filename}_${new Date().toISOString().split('T')[0]}.pdf`);
};

